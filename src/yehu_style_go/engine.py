def find_bundled_engine(roots) -> tuple[Path, Path] | None:
    """Find a KataGo executable and .bin.gz model inside a portable package tree."""
    seen: set[Path] = set()
    for root in roots:
        root = Path(root)
        try:
            root = root.resolve()
        except OSError:
            continue
        if root in seen or not root.is_dir():
            continue
        seen.add(root)
        executable = None
        for candidate in (root / "katago" / "katago.exe", root / "katago.exe"):
            if candidate.is_file():
                executable = candidate
                break
        if executable is None:
            executable = next((path for path in root.rglob("katago.exe") if path.is_file()), None)
        if executable is None:
            continue
        models = sorted(path for path in root.rglob("*.bin.gz") if path.is_file())
        if not models:
            models = sorted(path for path in root.rglob("*.txt.gz") if path.is_file())
        if models:
            return executable, models[0]
    return None


def bundled_engine_roots() -> list[Path]:
    """Likely locations for the optional portable 引擎/engines folder."""
    import sys
    if getattr(sys, "frozen", False):
        base = Path(sys.executable).resolve().parent
    else:
        base = Path(__file__).resolve().parents[2]
    candidates = [
        base / "engines", base / "引擎",
        base.parent / "engines", base.parent / "引擎",
        Path.cwd() / "engines", Path.cwd() / "引擎",
    ]
    result: list[Path] = []
    for path in candidates:
        try:
            resolved = path.resolve()
        except OSError:
            continue
        if resolved not in result:
            result.append(resolved)
    return result


class EngineError(RuntimeError):
    pass


@dataclass
class EngineSettings:
    executable: str = ""
    model: str = ""
    visits: int = 120

    def validate(self) -> None:
        if not self.executable or not Path(self.executable).is_file():
            raise EngineError("请先在设置中选择 KataGo 可执行文件")
        if not self.model or not Path(self.model).is_file():
            raise EngineError("请先在设置中选择 KataGo 网络模型（.bin.gz）")
        if not 1 <= self.visits <= 10000:
            raise EngineError("分析访问次数必须在 1 到 10000 之间")

    @property
    def key(self) -> str:
        details = asdict(self)
        for name in ("executable", "model"):
            path = Path(details[name])
            if path.is_file():
                details[f"{name}_size"] = path.stat().st_size
                details[f"{name}_mtime"] = path.stat().st_mtime_ns
        details["config"] = DEFAULT_CONFIG
        return hashlib.sha256(json.dumps(details, sort_keys=True).encode()).hexdigest()[:24]


class KataGo:
    """One serialized JSON-protocol session; reader threads keep pipes from blocking."""

    def __init__(self, settings: EngineSettings, work_dir: Path) -> None:
        self.settings = settings
        settings.validate()
        work_dir.mkdir(parents=True, exist_ok=True)
        config = work_dir / "analysis.cfg"
        config.write_text(DEFAULT_CONFIG, encoding="utf-8")
        self.responses: queue.Queue[dict[str, Any] | None] = queue.Queue()
        self.errors: deque[str] = deque(maxlen=40)
        self.lock = threading.Lock()
        self.process = subprocess.Popen(
            [str(Path(settings.executable).resolve()), "analysis", "-model",
             str(Path(settings.model).resolve()), "-config", str(config.resolve())],
            cwd=work_dir,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            errors="replace",
            bufsize=1,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        threading.Thread(target=self._read_stdout, daemon=True).start()
        threading.Thread(target=self._read_stderr, daemon=True).start()

    def _read_stdout(self) -> None:
        assert self.process.stdout is not None
        try:
            for line in self.process.stdout:
                try:
                    self.responses.put(json.loads(line))
                except json.JSONDecodeError:
                    self.errors.append(line.strip())
        finally:
            self.responses.put(None)

    def _read_stderr(self) -> None:
        assert self.process.stderr is not None
        for line in self.process.stderr:
            self.errors.append(line.strip())

    def query(
        self,
        request: dict[str, Any],
        expected: int = 1,
        progress: Callable[[int, int], None] | None = None,
        timeout: float = 600,
        cancel: threading.Event | None = None,
    ) -> list[dict[str, Any]]:
        with self.lock:
            if self.process.poll() is not None:
                raise EngineError("KataGo 未在运行：\n" + "\n".join(self.errors))
            query_id = uuid.uuid4().hex
            request = {**request, "id": query_id}
            assert self.process.stdin is not None
            try:
                self.process.stdin.write(json.dumps(request) + "\n")
                self.process.stdin.flush()
            except (OSError, ValueError) as error:
                raise EngineError("无法向 KataGo 发送请求") from error
            results: dict[int, dict[str, Any]] = {}
            deadline = time.monotonic() + timeout
            while len(results) < expected:
                if cancel is not None and cancel.is_set():
                    self.close()
                    raise EngineError("任务已取消")
                if time.monotonic() > deadline:
                    self.close()
                    raise EngineError("KataGo 响应超时：\n" + "\n".join(self.errors))
                try:
                    response = self.responses.get(timeout=0.25)
                except queue.Empty:
                    continue
                if response is None:
                    raise EngineError("KataGo 已退出：\n" + "\n".join(self.errors))
                if response.get("id") != query_id:
                    continue
                if "error" in response:
                    raise EngineError(str(response["error"]))
                if response.get("isDuringSearch", False) or "rootInfo" not in response:
                    continue
                turn = response.get("turnNumber", 0)
                results[turn] = response
                if progress:
                    progress(len(results), expected)
                deadline = time.monotonic() + timeout
            return [results[turn] for turn in sorted(results)]

    def analyze_game(
        self,
        game: GameRecord,
        progress: Callable[[int, int], None] | None = None,
        cancel: threading.Event | None = None,
    ) -> dict[str, Any]:
        request = self.position_request(game.moves, game.board_size, game.komi, game.rules)
        request["initialStones"] = [
            [color, xy_to_gtp(x, y, game.board_size)]
            for color, points in (("B", game.setup_black), ("W", game.setup_white))
            for x, y in points
        ]
        request["initialPlayer"] = game.first_property(
            "PL", "W" if game.setup_black else "B"
        )
        request["analyzeTurns"] = list(range(len(game.moves) + 1))
        responses = self.query(request, len(game.moves) + 1, progress, cancel=cancel)
        return {"engine_key": self.settings.key, "perspective": "B", "positions": responses}

    def position_request(
        self, moves: list[Move], size: int = 19, komi: float = 7.5, rules: str = "chinese"
    ) -> dict[str, Any]:
        return {
            "moves": [[move.color, xy_to_gtp(move.x, move.y, size)] for move in moves],
            "boardXSize": size,
            "boardYSize": size,
            "rules": rules,
            "komi": komi,
            "maxVisits": self.settings.visits,
            "includePolicy": True,
        }

    def analyze_position(
        self, moves: list[Move], size: int = 19, komi: float = 7.5
    ) -> dict[str, Any]:
        return self.query(self.position_request(moves, size, komi))[0]

    def close(self) -> None:
        if self.process.poll() is None:
            self.process.terminate()
            try:
                self.process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=5)
        for pipe in (self.process.stdin, self.process.stdout, self.process.stderr):
            if pipe is not None:
                try:
                    pipe.close()
                except OSError:
                    pass

    def __enter__(self) -> KataGo:
        return self

    def __exit__(self, *args: Any) -> None:
        self.close()


def move_report(game: GameRecord, analysis: dict[str, Any], player: str) -> list[dict[str, Any]]:
    positions = {position["turnNumber"]: position for position in analysis.get("positions", [])}
    color = game.color_for(player)
    sign = 1 if color == "B" else -1
    rows = []
    for index, move in enumerate(game.moves):
        if move.color != color or index not in positions or index + 1 not in positions:
            continue
        before = positions[index]
        after = positions[index + 1]
        before_score = before["rootInfo"].get("scoreLead", 0)
        after_score = after["rootInfo"].get("scoreLead", 0)
        loss = max(0.0, (before_score - after_score) * sign)
        candidates = sorted(before.get("moveInfos", []),
                            key=lambda info: info.get("order", 999))
        best = candidates[0] if candidates else {}
        reports = []
        for info in candidates[:8]:
            candidate_score = info.get("scoreLead")
            candidate_winrate = info.get("winrate")
            if isinstance(candidate_winrate, (int, float)):
                candidate_winrate = (candidate_winrate if color == "B"
                                     else 1 - candidate_winrate)
            else:
                candidate_winrate = None
            reports.append({
                "move": info.get("move", "—"),
                "order": info.get("order", 999),
                "pv": info.get("pv", []),
                "visits": info.get("visits"),
                "score": (float(candidate_score) * sign
                          if isinstance(candidate_score, (int, float)) else None),
                "winrate": candidate_winrate,
            })
        top_score = next((item["score"] for item in reports
                          if item["score"] is not None), None)
        for item in reports:
            if item["score"] is not None and top_score is not None:
                item["loss"] = max(0.0, top_score - item["score"])
            else:
                item["loss"] = None
        winrate = after["rootInfo"].get("winrate", 0.5)
        rows.append({
            "turn": index + 1,
            "move": xy_to_gtp(move.x, move.y, game.board_size),
            "best": best.get("move", "—"),
            "pv": best.get("pv", []),
            "loss": loss,
            "score": after_score * sign,
            "winrate": winrate if color == "B" else 1 - winrate,
            "label": "严重失误" if loss >= 8 else "失误" if loss >= 3 else "正常",
            "candidates": reports,
        })
    return rows
